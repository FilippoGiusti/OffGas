class DataLogger:

    def __init__(self, filename):

        self.filename = filename

        if not os.path.exists(self.filename):

            with open(self.filename, "w", newline="") as file:

                writer = csv.writer(file)

                writer.writerow([
                    "timestamp",
                    "garage_id",
                    "gas",
                    "fan_state"
                ])

    def save(self, payload):

        with open(self.filename, "a", newline="") as file:

            writer = csv.writer(file)

            writer.writerow([
                payload["timestamp"],
                payload["garage_id"],
                payload["gas"],
                payload["fan_state"]
            ])


# ===============================
# SYSTEM LOGGER
# ===============================

class SystemLogger:

    def __init__(self, filename):

        self.filename = filename

        if not os.path.exists(self.filename):

            with open(self.filename, "w") as f:

                f.write(
                    "OFFGAS SYSTEM LOGS\n"
                    "============================================================\n\n"
                )

    def log(self,
            event,
            garage="G1",
            gas=None,
            topic=None,
            status="INFO"):

        timestamp = datetime.datetime.now().isoformat()

        line = (
            f"[{timestamp}] "
            f"EVENT={event} | "
            f"GARAGE={garage} | "
            f"GAS={gas} | "
            f"TOPIC={topic} | "
            f"STATUS={status}\n"
        )

        with open(self.filename, "a") as f:
            f.write(line)


# ===============================
# RANDOM FOREST PREDICTION ENGINE
# ===============================

class RandomForestPredictionEngine:
    """
    Future-development prediction module.

    It loads gas_rf_model.pkl generated by train_randomforest.py and predicts
    the future gas value for G1, normally 30 seconds ahead.

    The model uses only local G1 history because the current prototype CSV
    contains only G1 samples.
    """

    def __init__(self, model_path):

        self.model = None
        self.feature_columns = []
        self.horizon_seconds = 30
        self.lag_steps = 6

        self.history = []
        self.max_history = 30
        self.start_timestamp = None

        if os.path.exists(model_path):

            try:

                bundle = joblib.load(model_path)

                if isinstance(bundle, dict) and "model" in bundle:

                    self.model = bundle["model"]
                    self.feature_columns = bundle.get(
                        "feature_columns",
                        []
                    )
                    self.horizon_seconds = bundle.get(
                        "horizon_seconds",
                        30
                    )
                    self.lag_steps = bundle.get(
                        "lag_steps",
                        6
                    )

                else:

                    # Fallback if someone saved only the raw sklearn model.
                    self.model = bundle
                    self.feature_columns = [
                        "gas_t",
                        "gas_lag_1",
                        "gas_lag_2",
                        "gas_lag_3",
                        "gas_lag_4",
                        "gas_lag_5",
                        "gas_lag_6",
                        "rolling_mean_3",
                        "rolling_mean_6",
                        "rolling_std_6",
                        "slope_6",
                        "fan_state"
                    ]

                print("[RF] RandomForest model loaded")

            except Exception as e:

                print(f"[RF ERROR] {e}")

        else:

            print("[RF] No trained RandomForest model found")

    def _parse_timestamp(self, timestamp):

        if isinstance(timestamp, datetime.datetime):
            return timestamp

        try:
            return datetime.datetime.fromisoformat(
                str(timestamp)
            )

        except Exception:
            return datetime.datetime.now()

    def _fan_to_int(self, fan_state):

        if isinstance(fan_state, bool):
            return int(fan_state)

        return str(fan_state).lower() in [
            "true",
            "1",
            "yes",
            "on"
        ]

    def _rolling_mean(self, values):

        if not values:
            return 0.0

        return sum(values) / len(values)

    def _rolling_std(self, values):

        if len(values) <= 1:
            return 0.0

        mean = self._rolling_mean(values)

        variance = sum(
            (value - mean) ** 2 for value in values
        ) / len(values)

        return variance ** 0.5

    def _build_features(self,
                        gas_value,
                        fan_state,
                        timestamp):

        timestamp = self._parse_timestamp(timestamp)

        if self.start_timestamp is None:
            self.start_timestamp = timestamp

        elapsed_seconds = (
            timestamp - self.start_timestamp
        ).total_seconds()

        current_gas = float(gas_value)

        features = {
            "gas_t": current_gas,
            "fan_state": int(self._fan_to_int(fan_state))
        }

        # Lag features.
        # If there are not enough previous samples, fill with current gas.
        for lag in range(1, self.lag_steps + 1):

            if len(self.history) > lag:
                features[f"gas_lag_{lag}"] = float(
                    self.history[-lag - 1]
                )

            else:
                features[f"gas_lag_{lag}"] = current_gas

        last_3 = self.history[-3:]
        last_6 = self.history[-6:]

        features["rolling_mean_3"] = self._rolling_mean(last_3)
        features["rolling_mean_6"] = self._rolling_mean(last_6)
        features["rolling_std_6"] = self._rolling_std(last_6)

        if len(self.history) > self.lag_steps:
            features["slope_6"] = (
                current_gas - float(self.history[-self.lag_steps - 1])
            ) / self.lag_steps

        else:
            features["slope_6"] = 0.0

        return features

    def predict(self,
                gas_value,
                fan_state,
                timestamp):

        # Always update local history, even if the model is missing.
        self.history.append(
            float(gas_value)
        )

        if len(self.history) > self.max_history:
            self.history.pop(0)

        if self.model is None:
            return None

        try:

            features = self._build_features(
                gas_value=gas_value,
                fan_state=fan_state,
                timestamp=timestamp
            )

            row = [
                features.get(column, 0.0)
                for column in self.feature_columns
            ]

            prediction = self.model.predict([
                row
            ])

            return int(
                round(float(prediction[0]))
            )

        except Exception as e:

            print(f"[RF ERROR] {e}")

            return None


