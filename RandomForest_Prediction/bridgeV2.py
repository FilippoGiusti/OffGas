class FanController:

    def __init__(self, bluetooth):

        self.bluetooth = bluetooth

        self.fan_state = False
        self.manual_override = False

    def force_on(self):

        self.fan_state = True

        self.bluetooth.send_command(
            "FAN_ON\n"
        )

    def force_off(self):

        self.fan_state = False

        self.bluetooth.send_command(
            "FAN_OFF\n"
        )

    def set_auto(self):

        self.manual_override = False


# ===============================
# MQTT MANAGER
# ===============================

class MQTTManager:

    def __init__(self, config, fan, bridge):

        self.client = mqtt.Client(
            mqtt.CallbackAPIVersion.VERSION2
        )

        self.client.connect(
            config.MQTT_BROKER,
            config.MQTT_PORT
        )

        self.client.loop_start()

        self.topic_telemetry = config.TOPIC_TELEMETRY
        self.topic_alerts = config.TOPIC_ALERTS
        self.topic_commands = config.TOPIC_COMMANDS

        self.fan = fan
        self.bridge = bridge

        self.client.on_message = self.on_message

    def publish(self, payload):

        self.client.publish(
            self.topic_telemetry,
            json.dumps(payload)
        )

    def subscribe(self):

        self.client.subscribe(
            self.topic_commands
        )

    def _update_threshold_from_node_red(self, cmd):

        if not isinstance(cmd, dict):
            return

        threshold = None

        if "threshold" in cmd:
            threshold = cmd.get("threshold")

        elif "effective_threshold" in cmd:
            threshold = cmd.get("effective_threshold")

        if threshold is None:
            return

        try:

            self.bridge.current_threshold = float(threshold)

        except (TypeError, ValueError):

            pass

    def on_message(self, client, userdata, msg):

        try:

            raw = msg.payload.decode().strip()

            self.bridge.syslog.log(
                event="COMMAND_RECEIVED",
                gas=self.bridge.last_gas,
                topic=self.topic_commands,
                status="INFO"
            )

            try:

                cmd = json.loads(raw)

                # V2 addition:
                # Store the dynamic threshold computed by Node-RED.
                # RandomForest uses this threshold only to decide whether
                # its predicted value would cross the current safety limit.
                self._update_threshold_from_node_red(cmd)

                self.bridge.last_node_red_command = cmd

                if self.fan.manual_override:
                    return

                if cmd.get("mode") == "STD":

                    if (
                        cmd.get("anomaly")
                        or
                        cmd.get("predicted_crossing")
                    ):

                        self.fan.force_on()

                    else:

                        self.fan.force_off()

                return

            except json.JSONDecodeError:

                cmd = raw

            if cmd in ("FAN_ON", "ON"):

                self.fan.manual_override = True
                self.fan.force_on()

            elif cmd in ("FAN_OFF", "OFF"):

                self.fan.manual_override = True
                self.fan.force_off()

            elif cmd in ("AUTO", "AUTO_MODE"):

                self.fan.set_auto()

        except Exception as e:

            print(f"[MQTT ERROR] {e}")

            self.bridge.syslog.log(
                event="MQTT_ERROR",
                gas=self.bridge.last_gas,
                topic=self.topic_commands,
                status="ERROR"
            )


