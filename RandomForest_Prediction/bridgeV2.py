# BRIDGE CORE
# ===============================

class Bridge:

    def __init__(self):

        self.config = Config()

        self.bluetooth = BluetoothManager(
            self.config
        )

        self.fan = FanController(
            self.bluetooth
        )

        self.mqtt = MQTTManager(
            self.config,
            self.fan,
            self
        )

        # CSV DATASET
        self.logger = DataLogger(
            self.config.CSV_FILE
        )

        # SYSTEM LOGS
        self.syslog = SystemLogger(
            self.config.LOG_FILE
        )

        # RANDOM FOREST PREDICTION ENGINE
        self.rf = RandomForestPredictionEngine(
            self.config.MODEL_FILE
        )

        self.last_gas = None

        # Dynamic threshold received from Node-RED commands.
        self.current_threshold = None

        # Last JSON command received from Node-RED.
        self.last_node_red_command = None

    def start(self):

        self.bluetooth.connect()

        self.syslog.log(
            event="BRIDGE_CONNECTED",
            topic=self.config.TOPIC_TELEMETRY,
            status="OK"
        )

        self.mqtt.subscribe()

        self.syslog.log(
            event="MQTT_CONNECTED",
            topic=self.config.TOPIC_TELEMETRY,
            status="OK"
        )

        try:

            while True:

                data = self.bluetooth.read_line()

                if data:
                    self.process(data)

                time.sleep(0.2)

        except KeyboardInterrupt:

            self.stop()

    def process(self, data):

        self.last_gas = data["gas"]

        # ==========================
        # RANDOM FOREST PREDICTION
        # ==========================

        rf_predicted_gas = self.rf.predict(
            gas_value=data["gas"],
            fan_state=self.fan.fan_state,
            timestamp=data["timestamp"]
        )

        rf_predicted_crossing = False

        if (
            rf_predicted_gas is not None
            and self.current_threshold is not None
        ):

            rf_predicted_crossing = (
                rf_predicted_gas >= self.current_threshold
            )

        if rf_predicted_crossing:

            print(
                f"[RF] PREDICTED CROSSING | "
                f"GAS={data['gas']} | "
                f"PREDICTED_{self.config.RF_PREDICTION_HORIZON_SECONDS}s={rf_predicted_gas} | "
                f"THRESHOLD={self.current_threshold}"
            )

            self.syslog.log(
                event="RF_PREDICTED_CROSSING",
                gas=data["gas"],
                topic=self.config.TOPIC_TELEMETRY,
                status="WARNING"
            )

        # ==========================
        # PAYLOAD
        # ==========================

        payload = {
            "garage_id": "G1",
            "gas": data["gas"],
            "timestamp": data["timestamp"],
            "fan_state": self.fan.fan_state,

            # V2 telemetry fields
            "rf_predicted_gas_30s": rf_predicted_gas,
            "rf_prediction_horizon_sec": self.config.RF_PREDICTION_HORIZON_SECONDS,
            "rf_predicted_crossing": rf_predicted_crossing,
            "node_red_threshold": self.current_threshold
        }

        # ==========================
        # MQTT
        # ==========================

        self.mqtt.publish(payload)

        # ==========================
        # CSV SAVE
        # ==========================

        self.logger.save(payload)

        # ==========================
        # SYSTEM LOG
        # ==========================

        self.syslog.log(
            event="TELEMETRY_SENT",
            gas=data["gas"],
            topic=self.config.TOPIC_TELEMETRY,
            status="INFO"
        )

    def stop(self):

        self.syslog.log(
            event="SYSTEM_STOPPED",
            gas=self.last_gas,
            status="WARNING"
        )

        self.fan.force_off()

        if self.bluetooth.ser:
            self.bluetooth.ser.close()


