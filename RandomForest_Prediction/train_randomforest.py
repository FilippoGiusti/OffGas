"""
train_randomforest.py

Future-development demo for OffGas:
- reads gas_data.csv generated by the bridge
- trains a RandomForestRegressor
- predicts the gas value at a configurable future horizon, default 30 seconds
- saves a model bundle used by bridgeV2.py

Usage:
    python train_randomforest.py
    python train_randomforest.py --csv gas_data.csv --model gas_rf_model.pkl --horizon-seconds 30
"""

import argparse
import datetime
import os
import re

import joblib
import numpy as np
import pandas as pd

from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score


# ===============================
# CONFIGURATION
# ===============================

DEFAULT_CSV_FILE = "gas_data.csv"
DEFAULT_LOG_FILE = "system_logs.txt"
DEFAULT_MODEL_FILE = "gas_rf_model.pkl"

TARGET_GARAGE = "G1"
DEFAULT_HORIZON_SECONDS = 30

LAG_STEPS = 6


# ===============================
# OPTIONAL LOG PARSER
# ===============================

def parse_system_logs(log_path):
    """
    Fallback parser.

    The CSV is the main training source. system_logs.txt is only useful if
    the CSV is missing or incomplete, because the logs contain telemetry
    timestamps and GAS values but not all training fields.
    """

    rows = []

    if not log_path or not os.path.exists(log_path):
        return pd.DataFrame(columns=[
            "timestamp",
            "garage_id",
            "gas",
            "fan_state"
        ])

    pattern = re.compile(
        r"\[(?P<timestamp>[^\]]+)\].*?"
        r"EVENT=(?P<event>[^|]+)\s*\|\s*"
        r"GARAGE=(?P<garage>[^|]+)\s*\|\s*"
        r"GAS=(?P<gas>[^|]+)"
    )

    with open(log_path, "r", encoding="utf-8", errors="ignore") as file:
        for line in file:
            match = pattern.search(line)

            if not match:
                continue

            event = match.group("event").strip()
            gas = match.group("gas").strip()

            if event != "TELEMETRY_SENT":
                continue

            if gas in ("None", "", "nan"):
                continue

            try:
                gas_value = int(float(gas))
            except ValueError:
                continue

            rows.append({
                "timestamp": match.group("timestamp").strip(),
                "garage_id": match.group("garage").strip(),
                "gas": gas_value,
                "fan_state": False
            })

    return pd.DataFrame(rows)


# ===============================
# DATASET LOADING
# ===============================

def load_dataset(csv_path, log_path=None, use_logs=False):
    """
    Load gas_data.csv.

    If --use-logs is enabled, system_logs.txt is merged as an additional
    fallback source. Duplicate timestamp/gas rows are removed.
    """

    frames = []

    if os.path.exists(csv_path):
        csv_df = pd.read_csv(csv_path)
        frames.append(csv_df)

    if use_logs:
        log_df = parse_system_logs(log_path)
        if not log_df.empty:
            frames.append(log_df)

    if not frames:
        raise FileNotFoundError(
            "No usable dataset found. Provide gas_data.csv or enable --use-logs with system_logs.txt."
        )

    df = pd.concat(frames, ignore_index=True)

    required_columns = [
        "timestamp",
        "garage_id",
        "gas",
        "fan_state"
    ]

    for column in required_columns:
        if column not in df.columns:
            if column == "garage_id":
                df[column] = TARGET_GARAGE
            elif column == "fan_state":
                df[column] = False
            else:
                raise ValueError(f"Missing required column: {column}")

    df["timestamp"] = pd.to_datetime(
        df["timestamp"],
        errors="coerce"
    )

    df["gas"] = pd.to_numeric(
        df["gas"],
        errors="coerce"
    )

    df["fan_state"] = df["fan_state"].astype(str).str.lower().isin([
        "true",
        "1",
        "yes",
        "on"
    ]).astype(int)

    df = df.dropna(
        subset=[
            "timestamp",
            "gas"
        ]
    )

    df["gas"] = df["gas"].astype(float)

    df = df.drop_duplicates(
        subset=[
            "timestamp",
            "garage_id",
            "gas"
        ]
    )

    df = df.sort_values(
        by=[
            "garage_id",
            "timestamp"
        ]
    ).reset_index(drop=True)

    return df


# ===============================
# FEATURE ENGINEERING
# ===============================

def estimate_sample_interval_seconds(df):
    deltas = (
        df["timestamp"]
        .diff()
        .dt.total_seconds()
        .dropna()
    )

    deltas = deltas[
        (deltas > 0) &
        (deltas < 120)
    ]

    if deltas.empty:
        return 5.0

    return float(deltas.median())


def build_training_table(df, target_garage, horizon_seconds):
    """
    Build lag-based time-series features.

    The model learns:
        recent gas history -> gas value after horizon_seconds

    With the current prototype, samples are usually produced every ~5 seconds,
    so a 30 second prediction corresponds approximately to 6 samples ahead.
    """

    data = df[
        df["garage_id"] == target_garage
    ].copy()

    if data.empty:
        raise ValueError(f"No rows found for garage_id={target_garage}")

    data = data.sort_values("timestamp").reset_index(drop=True)

    sample_interval_seconds = estimate_sample_interval_seconds(data)

    horizon_steps = max(
        1,
        int(round(horizon_seconds / sample_interval_seconds))
    )

    data["gas_t"] = data["gas"]

    for lag in range(1, LAG_STEPS + 1):
        data[f"gas_lag_{lag}"] = data["gas"].shift(lag)

    data["rolling_mean_3"] = (
        data["gas"]
        .rolling(window=3, min_periods=3)
        .mean()
    )

    data["rolling_mean_6"] = (
        data["gas"]
        .rolling(window=6, min_periods=6)
        .mean()
    )

    data["rolling_std_6"] = (
        data["gas"]
        .rolling(window=6, min_periods=6)
        .std(ddof=0)
    )

    data["slope_6"] = (
        data["gas"] - data["gas"].shift(LAG_STEPS)
    ) / LAG_STEPS

    target_column = f"gas_next_{horizon_seconds}s"
    data[target_column] = data["gas"].shift(-horizon_steps)

    feature_columns = [
        "gas_t",
        "gas_lag_1",
        "gas_lag_2",
        "gas_lag_3",
        "gas_lag_4",
        "gas_lag_5",
        "gas_lag_6",
        "rolling_mean_3",
        "rolling_mean_6",
        "rolling_std_6",
        "slope_6",
        "fan_state"
    ]

    training_table = data.dropna(
        subset=feature_columns + [
            target_column
        ]
    ).reset_index(drop=True)

    if len(training_table) < 30:
        raise ValueError(
            "Not enough usable rows after feature engineering. "
            "Collect more gas_data.csv samples before training."
        )

    return (
        training_table,
        feature_columns,
        target_column,
        horizon_steps,
        sample_interval_seconds
    )


# ===============================
# TRAINING
# ===============================

def train_model(training_table, feature_columns, target_column):
    """
    Chronological split: the first 80% is training, the last 20% is test.
    This is better than random shuffling for time-series data.
    """

    X = training_table[feature_columns].to_numpy()
    y = training_table[target_column].to_numpy()

    split_index = int(len(training_table) * 0.8)

    if split_index < 20:
        split_index = len(training_table)

    X_train = X[:split_index]
    y_train = y[:split_index]

    X_test = X[split_index:]
    y_test = y[split_index:]

    model = RandomForestRegressor(
        n_estimators=300,
        max_depth=8,
        min_samples_leaf=2,
        random_state=42,
        n_jobs=-1
    )

    model.fit(
        X_train,
        y_train
    )

    metrics = {
        "train_rows": int(len(X_train)),
        "test_rows": int(len(X_test))
    }

    if len(X_test) > 0:
        predictions = model.predict(X_test)
        baseline_predictions = X_test[:, 0]

        metrics.update({
            "mae": float(mean_absolute_error(y_test, predictions)),
            "rmse": float(np.sqrt(mean_squared_error(y_test, predictions))),
            "r2": float(r2_score(y_test, predictions)),
            "baseline_mae_current_gas": float(mean_absolute_error(y_test, baseline_predictions))
        })

    else:
        metrics.update({
            "mae": None,
            "rmse": None,
            "r2": None,
            "baseline_mae_current_gas": None
        })

    # After validation, retrain on the complete dataset for deployment/demo use.
    final_model = RandomForestRegressor(
        n_estimators=300,
        max_depth=8,
        min_samples_leaf=2,
        random_state=42,
        n_jobs=-1
    )

    final_model.fit(
        X,
        y
    )

    return final_model, metrics


# ===============================
# MAIN
# ===============================

def main():
    parser = argparse.ArgumentParser(
        description="Train a RandomForest model for OffGas next-value prediction."
    )

    parser.add_argument(
        "--csv",
        default=DEFAULT_CSV_FILE,
        help="Path to gas_data.csv"
    )

    parser.add_argument(
        "--logs",
        default=DEFAULT_LOG_FILE,
        help="Path to system_logs.txt"
    )

    parser.add_argument(
        "--model",
        default=DEFAULT_MODEL_FILE,
        help="Output model path"
    )

    parser.add_argument(
        "--garage",
        default=TARGET_GARAGE,
        help="Garage ID to train on. Default: G1"
    )

    parser.add_argument(
        "--horizon-seconds",
        type=int,
        default=DEFAULT_HORIZON_SECONDS,
        help="Prediction horizon in seconds. Default: 30"
    )

    parser.add_argument(
        "--use-logs",
        action="store_true",
        help="Merge telemetry rows parsed from system_logs.txt"
    )

    args = parser.parse_args()

    df = load_dataset(
        csv_path=args.csv,
        log_path=args.logs,
        use_logs=args.use_logs
    )

    (
        training_table,
        feature_columns,
        target_column,
        horizon_steps,
        sample_interval_seconds
    ) = build_training_table(
        df=df,
        target_garage=args.garage,
        horizon_seconds=args.horizon_seconds
    )

    model, metrics = train_model(
        training_table=training_table,
        feature_columns=feature_columns,
        target_column=target_column
    )

    bundle = {
        "model": model,
        "feature_columns": feature_columns,
        "target_column": target_column,
        "target_garage": args.garage,
        "horizon_seconds": args.horizon_seconds,
        "horizon_steps": horizon_steps,
        "sample_interval_seconds": sample_interval_seconds,
        "lag_steps": LAG_STEPS,
        "metrics": metrics,
        "created_at": datetime.datetime.now().isoformat(),
        "description": (
            "OffGas RandomForestRegressor model. "
            "It predicts the gas value at the configured future horizon "
            "using recent G1 gas history, rolling statistics, and fan_state."
        )
    }

    joblib.dump(
        bundle,
        args.model
    )

    print("RANDOM FOREST MODEL TRAINED")
    print(f"Rows in original dataset: {len(df)}")
    print(f"Rows used for supervised training: {len(training_table)}")
    print(f"Target garage: {args.garage}")
    print(f"Estimated sample interval: {sample_interval_seconds:.2f} seconds")
    print(f"Prediction horizon: {args.horizon_seconds} seconds")
    print(f"Prediction horizon in samples: {horizon_steps}")
    print(f"Model saved to: {args.model}")

    if metrics["mae"] is not None:
        print(f"MAE: {metrics['mae']:.3f}")
        print(f"RMSE: {metrics['rmse']:.3f}")
        print(f"R2: {metrics['r2']:.3f}")

        if metrics.get("baseline_mae_current_gas") is not None:
            print(f"Baseline MAE current gas: {metrics['baseline_mae_current_gas']:.3f}")


if __name__ == "__main__":
    main()
